const { test } = require('node:test');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { archiveRetiredStickers, resolveStickerPath, replacementId } = require('../app/retired-stickers.cjs');
const { Library } = require('../app/library.cjs');
const engine = require('../app/engine.cjs');

test('annotation stickers keep the original GIF for preview and have a timeline thumbnail', async (t) => {
  const data = await fs.mkdtemp(path.join(os.tmpdir(), 'cutting-gif-'));
  t.after(() => fs.rm(data, { recursive: true, force: true }));
  const library = new Library({ data }, engine);
  await fs.mkdir(library.cacheDir);
  const file = path.resolve(__dirname, '../assets/library/sticker/Straight Arrow Thin/Coral.gif');
  const asset = await library.inspect(file, 'sticker', 'Straight Arrow Thin');
  assert.equal(asset.kind, 'video');
  assert.equal(asset.hasAlpha, true);
  assert.equal(asset.previewPath ?? asset.path, file);
  assert.ok((await fs.stat(asset.thumbnail)).size > 0);
});

test('upgrading removes only the original stock, while old project sources and custom variants still open', async (t) => {
  const data = await fs.mkdtemp(path.join(os.tmpdir(), 'cutting-sticker-upgrade-'));
  t.after(() => fs.rm(data, { recursive: true, force: true }));
  const libraryDir = path.join(data, 'Library');
  const group = path.join(libraryDir, 'sticker', 'Retired');
  const other = path.join(libraryDir, 'sticker', 'Other');
  await fs.mkdir(group, { recursive: true });
  await fs.mkdir(other, { recursive: true });
  const original = Buffer.from('original sticker');
  const edited = Buffer.from('modified sticker');
  assert.equal(original.length, edited.length);
  const fingerprint = { size: original.length, sha256: createHash('sha256').update(original).digest('hex') };
  const catalog = { 'Retired/Red.gif': fingerprint, 'Retired/Blue.gif': fingerprint, 'Other/Red.gif': fingerprint };
  const red = path.join(group, 'Red.gif');
  const blue = path.join(group, 'Blue.gif');
  const custom = path.join(group, 'Mine.gif');
  const otherRed = path.join(other, 'Red.gif');
  await Promise.all([fs.writeFile(red, original), fs.writeFile(blue, edited), fs.writeFile(custom, original), fs.writeFile(otherRed, original)]);
  const ws = { data, libraryDir };
  const oldAsset = (file) => ({ id: 'asset-used-before-the-upgrade', path: file, category: 'sticker' });
  await archiveRetiredStickers(ws, catalog);
  assert.deepEqual((await fs.readdir(group)).sort(), ['Blue.gif', 'Mine.gif']);
  await assert.rejects(fs.access(other), { code: 'ENOENT' });
  const archived = await resolveStickerPath(oldAsset(red), ws, undefined, catalog);
  assert.notEqual(archived, red);
  assert.deepEqual(await fs.readFile(archived), original);
  assert.equal(await resolveStickerPath(oldAsset(blue), ws, undefined, catalog), blue);
  assert.deepEqual(await fs.readFile(blue), edited);
  const alias = path.join(data, 'Program', 'Library');
  const oldAlias = oldAsset(path.join(alias, 'sticker', 'Retired', 'Red.gif'));
  assert.equal(await resolveStickerPath(oldAlias, ws, alias, catalog), archived);
  const unrelated = path.join(data, 'another-folder', 'Retired', 'Red.gif');
  assert.equal(await resolveStickerPath(oldAsset(unrelated), ws, undefined, catalog), unrelated);
  await fs.writeFile(red, edited);
  await archiveRetiredStickers(ws, catalog);
  assert.deepEqual(await fs.readFile(red), edited);
  assert.equal(await resolveStickerPath(oldAsset(red), ws, undefined, catalog), archived);
  const newAsset = { ...oldAsset(red), id: replacementId('sticker', red), reusedStickerPath: true };
  assert.equal(await resolveStickerPath(newAsset, ws, undefined, catalog), red);
  const relinked = { ...newAsset, id: oldAsset(red).id };
  assert.equal(await resolveStickerPath(relinked, ws, undefined, catalog), red);
});
